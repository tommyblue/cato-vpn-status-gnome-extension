export function getLocaleCode(languageNames) {
  const firstLanguage =
    languageNames.length > 0 ? languageNames[0] : DEFAULT_LOCALE;
  return firstLanguage
    .toLowerCase()
    .replace("-", "_")
    .split("_")[0]
    .split(".")[0];
}

export function translate(locale, key) {
  const localeMessages = TRANSLATIONS[locale] ?? TRANSLATIONS[DEFAULT_LOCALE];
  return localeMessages[key] ?? TRANSLATIONS[DEFAULT_LOCALE][key] ?? key;
}
